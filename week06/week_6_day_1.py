import pandas as pd
from pathlib import Path

OUT = Path("/content/week-06/output")
OUT.mkdir(parents=True, exist_ok=True)

ledger = pd.read_csv("/content/stock_ledger.csv", parse_dates=["movement_date"])
br = pd.read_csv("/content/branches.csv", dtype=str)
br["capacity_sqft"] = br["warehouse_capacity"].str.extract(r"([\d.]+)")[0].astype(float)

ledger["month"] = ledger["movement_date"].dt.to_period("M")
kpi = ledger[ledger["movement_date"] <= "2024-12-31"]  # sales period, as in Weeks 4 and 5

out_m = (kpi[kpi["movement_type"] == "OUT"]
         .groupby(["branch_id", "month"])["quantity"].sum()
         .rename("out_units").reset_index())
in_m = (kpi[kpi["movement_type"] == "IN"]
        .groupby(["branch_id", "month"])["quantity"].sum()
        .rename("in_units").reset_index())

monthly = out_m.merge(in_m, on=["branch_id", "month"], how="outer").fillna(0)
n_months = kpi["month"].nunique()

thr = (monthly.groupby("branch_id")
       .agg(total_out=("out_units", "sum"),
            avg_out_per_month=("out_units", "mean"),
            peak_out_month=("out_units", "max"),
            total_in=("in_units", "sum"))
       .reset_index())
thr["out_to_in_ratio_pct"] = (thr["total_out"] / thr["total_in"] * 100).round(1)
thr["out_per_1000_sqft_per_month_PROVISIONAL"] = (
    thr["avg_out_per_month"] / (thr["branch_id"].map(br.set_index("branch_id")["capacity_sqft"]) / 1000)
).round(1)
thr = thr.sort_values("avg_out_per_month", ascending=False)

thr.to_csv(OUT / "week6_throughput_by_branch.csv", index=False)
monthly.to_csv(OUT / "week6_monthly_movements_by_branch.csv", index=False)

print("Months in sales period:", n_months)
print(thr.round(1).to_string(index=False))
print("\nTotal OUT:", f"{thr['total_out'].sum():,.0f}", "| Total IN:", f"{thr['total_in'].sum():,.0f}")

import pandas as pd
from pathlib import Path

OUT = Path("/content/week-06/output")
inv = pd.read_csv("/content/inventory_master.csv")
