# Average monthly sales per product and branch over the 72-month sales period
sales = pd.read_csv("/content/stock_ledger.csv", parse_dates=["movement_date"])
sales = sales[(sales["movement_type"] == "OUT") & (sales["movement_date"] <= "2024-12-31")].copy()
sales["month"] = sales["movement_date"].dt.to_period("M")
pm = (sales.groupby(["product_id", "branch_id", "month"])["quantity"].sum()
      .groupby(["product_id", "branch_id"]).mean()
      .rename("avg_monthly_out").reset_index())

df = inv.merge(pm, on=["product_id", "branch_id"], how="left").fillna({"avg_monthly_out": 0})
df["days_of_cover"] = df["current_stock"] / (df["avg_monthly_out"] / 30.4).replace(0, pd.NA)

df["flag_overstock"] = df["current_stock"] > df["max_stock"]
df["flag_understock"] = df["current_stock"] < df["safety_stock"]
df["flag_below_reorder"] = df["current_stock"] < df["reorder_level"]

def status(r):
    if r["avg_monthly_out"] == 0: return "no sales"
    if r["flag_understock"]: return "understock"
    if r["flag_overstock"]: return "overstock"
    return "within limits"

df["status_PROVISIONAL"] = df.apply(status, axis=1)
df.to_csv(OUT / "week6_overstock_understock_flags.csv", index=False)

print(df["status_PROVISIONAL"].value_counts().to_string())
print("\nFlags: overstock", int(df["flag_overstock"].sum()),
      "| understock", int(df["flag_understock"].sum()),
      "| below reorder", int(df["flag_below_reorder"].sum()))
print("\nMedian days of cover:", round(df["days_of_cover"].median(), 0))
print("\nTop 5 by avg monthly sales:")
print(df.nlargest(5, "avg_monthly_out")[["product_id", "branch_id", "current_stock",
      "max_stock", "avg_monthly_out", "days_of_cover", "status_PROVISIONAL"]].round(1).to_string(index=False))

import pandas as pd
