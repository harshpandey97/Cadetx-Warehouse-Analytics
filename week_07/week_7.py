import pandas as pd
from pathlib import Path

OUT = Path("/content/week-07/output")
OUT.mkdir(parents=True, exist_ok=True)

sup = pd.read_csv("/content/suppliers.csv", dtype=str)
po = pd.read_csv("/content/purchase_orders_header.csv", dtype=str)
lines = pd.read_csv("/content/purchase_orders_lines.csv", dtype=str)

po["total_cost"] = pd.to_numeric(po["total_cost"])
lines["quantity"] = pd.to_numeric(lines["quantity"])
lines["line_total"] = pd.to_numeric(lines["line_total"])

received = po[po["po_status"] == "Received"].copy()
print("Received POs:", len(received),
      "| Cancelled excluded:", int((po["po_status"] == "Cancelled").sum()))

# Check: header total matches sum of its lines (within 1 unit)
line_sum = lines.groupby("po_id")["line_total"].sum().rename("lines_sum")
chk = received.set_index("po_id")[["total_cost"]].join(line_sum)
mismatch = int(((chk["total_cost"] - chk["lines_sum"]).abs() > 1).sum())
print("Received POs where header total != sum of lines:", mismatch)

# Units per supplier, from received lines only
rl = lines[lines["po_id"].isin(received["po_id"])]
units = (rl.merge(received[["po_id", "supplier_id"]], on="po_id")
           .groupby("supplier_id")["quantity"].sum().rename("units"))

agg = (received.groupby("supplier_id")
       .agg(po_count=("po_id", "size"), purchase_value=("total_cost", "sum"))
       .join(units).reset_index())

df = sup[["supplier_id", "supplier_name", "product_category", "region"]].merge(
    agg, on="supplier_id", how="left")
df["value_share_pct"] = df["purchase_value"] / df["purchase_value"].sum() * 100
df["po_share_pct"] = df["po_count"] / df["po_count"].sum() * 100
df["unit_share_pct"] = df["units"] / df["units"].sum() * 100
df = df.sort_values("value_share_pct", ascending=False).round(1)
df.to_csv(OUT / "week7_supplier_contribution.csv", index=False)

print(df.to_string(index=False))
print("\nTotal purchase value:", f"{df['purchase_value'].sum():,.0f}")
print("Total units received:", f"{df['units'].sum():,.0f}")

