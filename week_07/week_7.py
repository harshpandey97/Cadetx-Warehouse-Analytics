# Check 1: how often is received date exactly equal to expected date?
same = (r["received_date"] == r["expected_delivery_date"]).mean() * 100
print(f"Received == expected date: {same:.1f}% of received POs")
print("Days late: min", (r["received_date"] - r["expected_delivery_date"]).dt.days.min(),
      "| max", (r["received_date"] - r["expected_delivery_date"]).dt.days.max())

# Metrics per supplier
r["days_late"] = (r["received_date"] - r["expected_delivery_date"]).dt.days
r["on_time"] = r["days_late"] <= 0
r["actual_lead_days"] = (r["received_date"] - r["order_date"]).dt.days
r["quoted_lead_days"] = (r["expected_delivery_date"] - r["order_date"]).dt.days

rel = (r.groupby("supplier_id")
       .agg(po_count=("po_id", "size"),
            on_time_rate_pct=("on_time", lambda s: s.mean() * 100),
            avg_days_late=("days_late", "mean"),
            median_actual_lead=("actual_lead_days", "median"),
            median_quoted_lead=("quoted_lead_days", "median"))
       .reset_index())
rel = sup[["supplier_id", "supplier_name", "reliability_score", "lead_time_days"]].merge(rel, on="supplier_id")
rel = rel.round(1).sort_values("on_time_rate_pct", ascending=False)
rel.to_csv(OUT / "week7_supplier_reliability.csv", index=False)
print(rel.to_string(index=False))

