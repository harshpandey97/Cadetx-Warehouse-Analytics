import pandas as pd
from pathlib import Path

OUT = Path("/content/week-07/output")
sup = pd.read_csv("/content/suppliers.csv", dtype=str)
po = pd.read_csv("/content/purchase_orders_header.csv", dtype=str)
lines = pd.read_csv("/content/purchase_orders_lines.csv", dtype=str)
cus = pd.read_csv("/content/customers.csv", dtype=str)
so = pd.read_csv("/content/sales_orders_header.csv", dtype=str)
sl = pd.read_csv("/content/sales_orders_lines.csv", dtype=str)

for df_, cols in [(lines, ["quantity", "unit_cost", "line_total"]),
                  (sl, ["quantity", "unit_price", "line_total"]),
                  (cus, ["total_purchase_value", "credit_limit", "current_balance"]),
                  (so, ["grand_total"])]:
    for c in cols:
        df_[c] = pd.to_numeric(df_[c], errors="coerce")

# ---- D3: supplier cost per unit, received POs only ----
rec_ids = po.loc[po["po_status"] == "Received", ["po_id", "supplier_id"]]
pl = lines.merge(rec_ids, on="po_id")
cpu = (pl.groupby("supplier_id")
       .agg(units=("quantity", "sum"), spend=("line_total", "sum")).reset_index())
cpu["avg_cost_per_unit"] = (cpu["spend"] / cpu["units"]).round(2)
cpu["vs_average_pct"] = ((cpu["avg_cost_per_unit"] / cpu["avg_cost_per_unit"].mean() - 1) * 100).round(2)
d3 = sup[["supplier_id", "supplier_name"]].merge(cpu, on="supplier_id").sort_values("avg_cost_per_unit")
d3.to_csv(OUT / "week7_supplier_cost_per_unit.csv", index=False)
print("D3: supplier cost per unit (received POs)")
print(d3.round(2).to_string(index=False))

# ---- E1: customer purchase behaviour (sales orders, sales period) ----
so_ok = so[so["order_status"].str.lower().isin(["delivered", "completed", "closed", "invoiced"])] \
    if so["order_status"].notna().any() else so
print("\nSales order status counts:")
print(so["order_status"].value_counts(dropna=False).to_string())

sales_val = so.groupby("customer_id")["grand_total"].sum().rename("order_value")
sales_n = so.groupby("customer_id").size().rename("orders")
cb = cus[["customer_id", "customer_type", "industry_segment", "region"]].set_index("customer_id") \
    .join(sales_val).join(sales_n).fillna({"order_value": 0, "orders": 0})
cb["value_rank"] = cb["order_value"].rank(ascending=False, method="first")
top50_share = cb.nlargest(50, "order_value")["order_value"].sum() / cb["order_value"].sum() * 100

print("\nE1: customer behaviour")
print("Customers with at least one order:", int((cb["orders"] > 0).sum()), "of", len(cb))
print("Orders per customer (mean):", round(cb["orders"].mean(), 1))
print("Top 50 customers' share of order value:", round(top50_share, 1), "%")
print("\nBy customer type:")
print(cb.groupby("customer_type").agg(customers=("orders", "size"),
      avg_orders=("orders", "mean"), value=("order_value", "sum")).round(1).to_string())
cb.to_csv(OUT / "week7_customer_behaviour.csv")

